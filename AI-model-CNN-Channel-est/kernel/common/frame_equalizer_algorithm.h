#ifndef FRAME_EQUALIZER_ALGORITHM_H
#define FRAME_EQUALIZER_ALGORITHM_H

// Equalizer selection is deliberately compile-time: each AIE image contains
// only one strategy and pays no per-symbol dispatch cost.
#define FRAME_EQUALIZER_ALGORITHM_LS 0
#define FRAME_EQUALIZER_ALGORITHM_LMS 1
#define FRAME_EQUALIZER_ALGORITHM_COMB 2
#define FRAME_EQUALIZER_ALGORITHM_STA 3
#define FRAME_EQUALIZER_ALGORITHM_CNN 4

#ifndef FRAME_EQUALIZER_ALGORITHM
#define FRAME_EQUALIZER_ALGORITHM FRAME_EQUALIZER_ALGORITHM_LS
#endif

#if FRAME_EQUALIZER_ALGORITHM != FRAME_EQUALIZER_ALGORITHM_LS && \
    FRAME_EQUALIZER_ALGORITHM != FRAME_EQUALIZER_ALGORITHM_LMS && \
    FRAME_EQUALIZER_ALGORITHM != FRAME_EQUALIZER_ALGORITHM_COMB && \
    FRAME_EQUALIZER_ALGORITHM != FRAME_EQUALIZER_ALGORITHM_STA && \
    FRAME_EQUALIZER_ALGORITHM != FRAME_EQUALIZER_ALGORITHM_CNN
#error "Unsupported FRAME_EQUALIZER_ALGORITHM"
#endif

#endif
