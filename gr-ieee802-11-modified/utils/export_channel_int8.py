#!/usr/bin/env python3
"""Copy NPU Q7 exports into compact, output-major CPU weight headers."""
import ast
import hashlib
from pathlib import Path
import re

import numpy as np


def main():
    root = Path(__file__).resolve().parents[1]
    source = root.parent / 'AI-model-CNN-Channel-est/kernel/channel_estimator/model'
    target = root / 'lib/equalizer/model'
    for split in ('by_frame', 'by_channel'):
        lines = ['// Generated by utils/export_channel_int8.py from NPU exports.',
                 '#pragma once', '#include <cstdint>', f'namespace int8_{split} {{']
        for kind, stem in (('cnn', 'ai'), ('mlp', 'updater_mlp')):
            path = source / f'frame_equalizer_channel_{stem}_weights_{split}.h'
            text = path.read_text()
            lines += [f'// {path.name}; SHA256 {hashlib.sha256(path.read_bytes()).hexdigest()}']
            gate = re.search(r'k(?:Ls)?GateSnrRatioX16 = (\d+)', text)[1]
            lines += [f'constexpr std::uint64_t {kind}_gate = {gate}ull;']
            for name, body in re.findall(r'int8_t k(W\d+)\[.*?= (\{.*?\});', text, re.S):
                values = np.array(ast.literal_eval(body.replace('{', '[').replace('}', ']')),
                                  dtype=np.int8)
                shapes = ({'W1': (12, 6, 7), 'W2': (12, 12, 5), 'W3': (2, 12, 3)}
                          if kind == 'cnn' else {'W1': (4, 64, 16), 'W2': (4, 16, 32)})
                if values.shape != shapes[name]:
                    raise ValueError(f'{path}: unexpected {name} shape {values.shape}')
                if kind == 'mlp':
                    # AIE stores padded [group,input,output]; CPU uses [group,output,input].
                    values = (values[:, :61, :16] if name == 'W1' else values[:, :16, :26]).transpose(0, 2, 1)
                flat = values.ravel()
                lines += [f'alignas(32) static constexpr std::int8_t {kind}_{name.lower()}[{flat.size}] = {{']
                lines += [', '.join(map(str, flat[i:i + 24])) + ',' for i in range(0, flat.size, 24)]
                lines += ['};']
        lines += ['}']
        (target / f'channel_int8_weights_{split}.h').write_text('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main()
